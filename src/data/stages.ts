/**
 * 水たまりの並び（ワールド座標）。
 *
 * ==========================================================================
 * **6箇所**（2026-09-13、人間が決めた）。魚の種類は2種のまま。
 * 叩く場所が多いと「どこを押しても当たりうる」ので、
 * 1歳半には押せるところが多いほうが効く（不変条件1・4c）。
 *
 * **2列×3行にする。** 3列×2行だと横の間隔が 1.38 しか取れず、
 * 当たり判定が半分になる（縦のほうが場所に余裕があるため）。
 *
 * **列を左に寄せてある**（2026-09-13）。魚は穴の**右**へ泳ぎ出るので、
 * 穴の右に体のぶん（約 1.1）の余白が要る。右の列を +1.42 に置いたままだと
 * 魚が画面の外（x > 2.30）へ出てしまう。
 * 左の列 −1.82・右の列 +0.43 にして、魚は −1.34 と +0.91 に出る。
 * **左の列をこれ以上左へ出さない** —— 穴の外周は 0.366 あるので、
 * −1.9 に置くと画面の端（±2.30）まで 3px しか残らず、縁が切れて見えた。
 * **行間は「画面上で」等間隔にする。** ワールドの y で等間隔にすると、
 * カメラが原点を見下ろしている（2.4°）ぶん**下の行ほど画面上で詰まる**。
 * 実測でそれをやったら 360×600 で 68.5px に落ちた
 * （CLAUDE.md「『縁の高さ』と『縁に見える高さ』は違う」と同じ話）。
 * 中段の −1.59 は、上端 0.68 と下端 −3.92 の**画面上の中点**を
 * 二分探索で求めた値。
 *
 * **いちばん上の行を地平線まで上げないこと**（2026-09-13、絵を見て直した）。
 * 上端を 0.68（地平線のすぐ下）まで上げると当たり判定は 71.3px まで稼げるが、
 * **遠くの丘と花畑の帯に水たまりが重なって、地平線に浮いて見えた**。
 * それは「ばあ！」が最後まで直せなかった欠点（上の段が空に浮く）そのもので、
 * **この設計が穴を地面に置くと決めた理由**（§3-2）。
 * 上端を 0.25（はっきり草地の上）に下げてある。
 *
 * 実測（いちばん近い組 ＝ 縦の隣どうし）:
 * Pixel 7 **89.1px** / iPhone 12 **79.5px** / 360×600 **63.4px** /
 * 横持ち 40.9px。
 * **360×600 では 70px に届かない。** 地平線まで上げれば届くが、
 * 上の「浮いて見える」を取り戻すことになるので採らなかった。
 * 実機（Pixel 7 / iPhone 12）はどちらも 79px 以上あるので、
 * **これ以上どうするかは人間の判断**（数を減らす／このまま／上げ直す）。
 *
 * **実測して置き直した**（2026-09-13）。4箇所だった版で
 * 360×600 の端末の半径が 62.2px まで縮み、いちばん近い組が
 * 左右ではなく**奥と手前の斜め**だと分かった。6箇所にした今は、
 * **縦にめいっぱい広げて等間隔に3行**置いている（行間 2.24）。
 *
 * 横に広げるのには**上限がある**。画面に入る x は Pixel 7（縦持ち）で
 * **±2.30 しかない**（fov 66°・z = 0・カメラから 7.2）。
 * **水面の半径ではなく、岸まで入れた外周 0.92 で測ること**（2026-09-13 に踏んだ）。
 * ±1.5 に置いたら岸の輪が切れていた（1.5 + 0.92 = 2.42 > 2.30）。
 * 中心は **±1.38** までしか置けないので、手前の列は ±1.35 にしてある。
 * **「置いたのに見えない」ときは、まず画面に入っているかを疑う**
 * （「ばあ！」で飾りを x = ±5.2 に並べて 9株のうち4株が画面の外だった）。
 *
 * **縦の間隔が「ばあ！」より狭い。** 地平線より下の帯に4つ収めるため。
 * 「ばあ！」の 2×2（±1.90 / ±2.00）は Pixel 7 の実測で
 * **隣との隙間が 2.0px しか無かった**ので、ここはさらに厳しい。
 * `HoleSystem.radiusAt()` が隣との距離を見て縮めるが、
 * **縮めた結果が 70px を下回るなら、4つを3つに減らすほうを選ぶ**
 * （小さい当たり判定より、数が少ないほうが1歳半には当たる）。
 * ==========================================================================
 */
