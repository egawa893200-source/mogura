/**
 * 時間の定数（設計書 §4-1 / §4-2 / §4-7）
 *
 * **数値はここだけに置く。** 遊びの手触りは「1つ変えて実機で見る」を
 * 繰り返すので、値が散らばると追えなくなる。
 *
 * ==========================================================================
 * **「ゆっくり出す」と「0フレームで反応する」は別の話**（2026-09-13、人間が決めた）。
 *
 * 遅くしているのは**魚が勝手に出てくる動き**で、
 * **叩いた瞬間の反応は 1フレームも遅らせない**（§4-3 の0フレーム原則）。
 * 「ばあ！」で害になった「ため」は、**押してから結果までの間**のことだった。
 * ==========================================================================
 */

export const TIMING = {
  /**
   * 出てくる**前**の「ため」（秒）。ここで「ばあっ！」と言う。
   *
   * ==========================================================================
   * **実機で「『ばあっ』する前にチラッと見えている」と言われた**（2026-09-13）。
   * 声と同時に動きはじめていたので、声が耳に届く前に姿が見えていた。
   *
   * 「**何も見えない状態で『ばあっ』と言って、それから出てくる**」が
   * 人間の指定。だから声を鳴らしてから動きはじめるまでの間を作る。
   *
   * **これは §4-3 が禁じている「ため」ではない。**
   * あちらは**押してから結果までの間**のことで、
   * ここは押していないとき（勝手に出てくる側）の間。
   * 叩いた瞬間の反応はいまも 0フレーム。
   * ==========================================================================
   */
  callSec: 0.38,

  /**
   * 水から出てくるのにかかる時間。
   *
   * **0.22秒では速すぎた**（v0.1）。出てくる動きそのものが見えないと
   * 「いつのまにか居た」になって、**出た瞬間を見逃す**。
   */
  risingSec: 0.65,

  /**
   * 出きってから自分で沈むまで。**介助（`assist`）がこの値を動かす。**
   *
   * 1歳半は指を画面へ運ぶまでに1秒近くかかるので、
   * 「見つける → 運ぶ → 当てる」に 2.6秒（v0.1）では足りない回が出る。
   */
  upSec: 4.0,

  /** 叩かれてから沈みきるまで（§4-3） */
  hitSec: 0.45,

  /** 叩かれずに自分で沈む */
  retreatSec: 0.5,

  /**
   * 次の出現までの間隔（秒）。
   *
   * v0.1 の 0.5〜1.4秒から伸ばした —— `up` を 4.0秒にしたので、
   * そのままだと常に上限まで出ていて画面が忙しくなる。
   * **上限に達しているあいだは、この時計を進めない**（`Spawner`）。
   */
  spawnMinSec: 0.8,
  spawnMaxSec: 2.0,
} as const;

/**
 * 難しさの自動調整（§4-7）。**得点でも罰でもなく、当たるようにするための介助。**
 *
 * **画面に表示しない。** 子どもにも保護者にも見せない。
 */
export const ASSIST = {
  /** これだけ続けて叩けなかったら伸ばす */
  missesToEase: 3,
  /** これだけ続けて叩けたら縮める */
  hitsToTighten: 5,
  /** 伸ばす／縮める幅（秒） */
  step: 1.2,
  /**
   * 動かせる範囲（秒）。
   *
   * **速い側の下限を割らないこと。** 当たるようになってきたからと
   * 速くしていくと、いちばん当たっていた設定を自分で壊す。
   */
  minUpSec: 3.2,
  maxUpSec: 5.2,
} as const;

