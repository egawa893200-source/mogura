/**
 * 難しさの自動調整（§4-7）。**得点でも罰でもなく、当たるようにするための介助。**
 *
 * **画面に表示しない。** 子どもにも保護者にも見せない。
 */
export const ASSIST = {
  /** これだけ続けて叩けなかったら伸ばす */
  missesToEase: 3,
  /**
   * これだけ続けて叩けたら縮める。
   *
   * **5 では縮みすぎた**（2026-09-16、実測）。沈んでいる最中の遅い指も
   * 「当たり」に数える（§4-3）ので、**当たりは5連続しやすく、
   * 外しは3連続しにくい**。結果、どんな遊びかたでも下限に張り付いた。
   * 縮める側だけ渋くする。
   */
  hitsToTighten: 8,
  /** 伸ばす／縮める幅（秒） */
  step: 1.2,
  /**
   * 動かせる範囲（秒）。
   *
   * **速い側の下限を割らないこと。** 当たるようになってきたからと
   * 速くしていくと、いちばん当たっていた設定を自分で壊す。
   *
   * ==========================================================================
   * **下限 3.2 は、設計書が警告していたとおりの壊れ方をしていた**
   * （2026-09-16、実機で「魚の戻るのが早くて、叩けない時が多々ある」）。
   *
   * 4通りの遊びかた（反応 1.2〜3.0秒・狙い外し 15〜30%）で 400秒ずつ
   * 回して測ったところ、**4通りとも最終的に下限 3.2 に張り付いた**。
   * 介助は「当たるようにするための仕掛け」なのに、**実際には常に
   * 難しくする方向にしか動いていなかった。**
   *
   * 下限そのものを上げる。**下限に張り付いても 5.0秒 + 沈む 0.9秒 = 5.9秒**
   * あるので、指が遅くても届く。
   * ==========================================================================
   */
  minUpSec: 5.0,
  maxUpSec: 9.0,
} as const;

