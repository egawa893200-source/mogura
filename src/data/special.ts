/**
 * ときどき出る特別な魚（設計書 §6-2）
 *
 * ==========================================================================
 * **抽選の当たりと、実際に出る割合は違う。**
 *
 * 「ばあ！」でサプライズの当たりに 1/3 をそのまま入れたら、
 * 2連続で出さない規則があったせいで**実測は 3.7〜4.0回に1回**だった。
 * ここでは**2連続を禁じる規則を入れない**ので、当たり＝割合になる。
 * それでも**必ず数えて確かめる**（単体テストが実測している）。
 *
 * **大きい と きんいろ は同時に出ない。** 乱数を1つだけ引いて、
 * その1本の数直線を3つに区切る。こうすると
 * 「きんいろを外したぶん大きいが出やすくなる」がそもそも起きない
 * （先に金を判定して残りで大を判定すると、大の実測は 1/20 ではなく
 * 1/17.1 になる）。
 * ==========================================================================
 */

export const SPECIAL = {
  /**
   * きんいろのさかな。**16回に1回。**
   *
   * 叩くと**花が1つ咲く＝その場でステージが変わる**（§5-3）。
   * ★10個を待たずに場面が変わるので、**自分が何かした**がいちばん伝わる。
   */
  goldChance: 1 / 16,

  /**
   * 大きいさかな。**20回に1回。**
   *
   * 実機で「大きい魚の出現頻度が高い」と言われた（2026-09-14）ので
   * レアにしてある。**そのとき出ていたのは大きい魚ではなく**、
   * 体高でそろえていたせいで細長い魚だけ 1.5倍の面積に描かれていたもの。
   * 面積でそろえて直したうえで、これを**本物のレア**として足す。
   */
  bigChance: 1 / 20,

  /** 大きいさかなの倍率。**出ている時間は変えない**（当てやすさは同じ） */
  bigScale: 1.4,

  /** 大きいさかなを叩いたときに増える★の数 */
  bigStars: 3,

  /**
   * きんいろの体の色。
   *
   * **材質の `color` に掛ける。** 3D モデルは頂点カラー、canvas の絵は
   * テクスチャを持っていて、どちらも `color` が掛け算で効く。
   * **白に近い金にする** —— 濃くすると体の模様が潰れて、
   * 「金色の何か」になって魚に見えない
   */
  goldColor: 0xffd24a,
} as const;

/** 1回の登場の種類。**大きい と きんいろ は同時に起きない** */
export type FishVariant = 'normal' | 'big' | 'gold';

/**
 * 乱数1つから種類を決める。
 *
 * **数直線を3つに区切るだけ。** 先に片方を判定して残りでもう片方を
 * 判定すると、2つ目の実測が指定した割合にならない。
 */
export function pickVariant(roll: number): FishVariant {
  if (roll < SPECIAL.goldChance) return 'gold';
  if (roll < SPECIAL.goldChance + SPECIAL.bigChance) return 'big';
  return 'normal';
}
