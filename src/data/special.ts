/**
 * ときどき出る特別な魚（設計書 §6-2）
 *
 * ==========================================================================
 * **抽選の当たりと、実際に出る割合は違う。**
 *
 * 「ばあ！」でサプライズの当たりに 1/3 をそのまま入れたら、
 * 2連続で出さない規則があったせいで**実測は 3.7〜4.0回に1回**だった。
 * ここでは**2連続を禁じる規則を入れない**ので、当たり＝割合になる。
 * それでも**必ず数えて確かめる**（単体テストが実測している）。
 *
 * **大きい と きんいろ は同時に出ない。** 乱数を1つだけ引いて、
 * その1本の数直線を3つに区切る。こうすると
 * 「きんいろを外したぶん大きいが出やすくなる」がそもそも起きない
 * （先に金を判定して残りで大を判定すると、大の実測は 1/20 ではなく
 * 1/17.1 になる）。
 * ==========================================================================
 */

export const SPECIAL = {
  /**
   * きんいろのさかな。**16回に1回。**
   *
   * 叩くと**花が1つ咲く＝その場でステージが変わる**（§5-3）。
   * ★10個を待たずに場面が変わるので、**自分が何かした**がいちばん伝わる。
   */
  goldChance: 1 / 16,

  /**
   * 大きいさかな。**20回に1回。**
   *
   * 実機で「大きい魚の出現頻度が高い」と言われた（2026-09-14）ので
   * レアにしてある。**そのとき出ていたのは大きい魚ではなく**、
   * 体高でそろえていたせいで細長い魚だけ 1.5倍の面積に描かれていたもの。
   * 面積でそろえて直したうえで、これを**本物のレア**として足す。
   */
  bigChance: 1 / 20,

  /**
   * 大きいさかなの倍率。**出ている時間は変えない**（当てやすさは同じ）。
   *
   * ==========================================================================
   * **1.4 では気づかれなかった**（2026-09-17）。実機で「追加要素はどうなったの」
   * と言われて測ったら、**高さの差は 17〜19px しかない**。
   * 魚は1匹ずつ違う水たまりに出るので、**隣に比べるものが無い**。
   * 並べて比べれば分かる差でも、単独では「いつもの魚」に見える。
   *
   * 1.4 → 1.75 に上げた。**ただし倍率だけでは揃わない**（下の `bigMaxHeight`）。
   * ==========================================================================
   */
  bigScale: 1.75,

  /**
   * 大きいさかなの高さの上限（ワールド）。
   *
   * ==========================================================================
   * **倍率だけだと、元から大きい魚が暴れる。**
   * エイは素の高さが 1.24 で、他（0.49〜0.59）の倍以上ある。
   * 1.75倍すると **2.17** になり、水たまり（縦半径 0.5）の4倍を超えて
   * 「水たまりから出てきた」ではなく「上に乗っている」に見える。
   *
   * 上限を掛けると、画面での増分がどの魚もそろう（実測 32〜39px）:
   *   きんぎょ 0.55 → 0.96 / はぎ 0.49 → 0.86 /
   *   くまのみ 0.59 → 1.03 / エイ 1.24 → 1.60（実効 1.29倍）
   * ==========================================================================
   */
  bigMaxHeight: 1.6,

  /** 大きいさかなを叩いたときに増える★の数 */
  bigStars: 3,

  /**
   * きんいろの体の色。
   *
   * **材質の `color` に掛ける。** 3D モデルは頂点カラー、canvas の絵は
   * テクスチャを持っていて、どちらも `color` が掛け算で効く。
   * **白に近い金にする** —— 濃くすると体の模様が潰れて、
   * 「金色の何か」になって魚に見えない
   */
  goldColor: 0xffd24a,
} as const;

/** 1回の登場の種類。**大きい と きんいろ は同時に起きない** */
export type FishVariant = 'normal' | 'big' | 'gold';

/**
 * 乱数1つから種類を決める。
 *
 * **数直線を3つに区切るだけ。** 先に片方を判定して残りでもう片方を
 * 判定すると、2つ目の実測が指定した割合にならない。
 */
export function pickVariant(roll: number): FishVariant {
  if (roll < SPECIAL.goldChance) return 'gold';
  if (roll < SPECIAL.goldChance + SPECIAL.bigChance) return 'big';
  return 'normal';
}

/**
 * サプライズ（§6-3）— 画面の下から大きく1匹。
 *
 * ==========================================================================
 * **抽選ではなく時計で出す**（2026-09-17）。
 *
 * 設計書は「3回に1回から始める」と書いているが、それは「ばあ！」の
 * **タップに紐づく**抽選の話。ぽこ！の魚は押さなくても出続けるので、
 * 出現数に紐づけると**よく叩く子ほどサプライズが増えて**、
 * 「大きいのが普通」になる（§6-3 が避けたいことそのもの）。
 * 時計なら遊びかたに依らない。
 *
 * **飽きが早ければ `minGapSec` / `maxGapSec` を上げること。**
 * ==========================================================================
 */
export const SURPRISE = {
  /** 次に出るまでの間隔（秒）。実測は単体テストが出す */
  minGapSec: 22,
  maxGapSec: 34,

  /**
   * 声だけ鳴らして姿を出さない時間。
   * **水たまりの魚（0.38秒）より長い** —— 大きいものが出る前触れなので、
   * 少し待たせたほうが「来るぞ」になる
   */
  callSec: 0.5,

  /**
   * 下から出てくる時間。
   * **大きいぶん、ゆっくり出す**（§6-3）。速いと驚かせるだけになる
   */
  riseSec: 0.9,

  /** 出きったまま待つ時間。**水たまりの魚より長い**（大きいので狙いやすい） */
  outSec: 3.2,

  /** 叩かれてから消えるまで */
  hitSec: 0.45,

  /** 叩かれずに沈む時間。**ゆっくり沈む**（大きいものが消えるのは目立つ） */
  sinkSec: 1.0,

  /** 叩いたときに増える★の数（§6-3） */
  stars: 5,

  /**
   * 見かけの高さ（ワールド）。
   *
   * 画面に入るのは縦 ±4.68 くらいなので、3.0 は**画面のおよそ1/3**。
   * **これ以上大きくしない** —— 画面を覆うと、下の水たまりが押せているのか
   * 分からなくなる（§3-4 の事故と同じ形）
   */
  height: 2.2,

  /**
   * 見かけの幅の上限（ワールド）。
   *
   * ==========================================================================
   * **高さでそろえると、横長の魚が画面から出る**（2026-09-17、絵で測った）。
   * きんぎょは横向きなので、高さ 2.2 にそろえると幅が **4.03** になる。
   * 390×844 の端末でこの奥行き（z = 1.4）に入るのは **3.48** しかなく、
   * **顔が左端で切れた**。尾が切れるのは許せるが、顔が切れるのは別物に見える。
   *
   * 3.2 は、いちばん狭い縦持ち（アスペクト 0.46）でも両端に余白が残る値。
   * ==========================================================================
   */
  maxWidth: 3.2,

  /**
   * 出てくる場所。**画面の中央**（左右どちらかに寄せると通り過ぎに見える）。
   *
   * **エイは見かけの中心がここより右にずれる。** 長い尾を含めた
   * 境界箱の中心が原点なので、尾が細いぶん「体」は右上に寄って見える。
   * 当たり判定は境界箱で測る（尾を押しても当たる）ので、そこは合っている
   */
  x: 0,
  /** 隠れている y（画面の下の外） */
  hiddenY: -7.4,
  /** 出きった y。**下の水たまりの列（-3.76）より下に芯を置く** */
  outY: -2.64,
  /** 水たまりより手前。**いちばん前に出す**（押す相手がこれだと分かるように） */
  z: 1.4,

  /** 体の向き（ラジアン）。斜めに構えて輪郭を見せる */
  yaw: -0.5,
} as const;
