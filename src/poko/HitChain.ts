/** 半音（周波数比）。1オクターブ＝12半音 */
const SEMITONE = 1.059463;

/**
 * 上がる段数の上限。
 *
 * `AudioBus.playOneShot` は 0.8〜1.25 に丸めるので、**4段目から上は
 * 鳴らしても同じ音**になる（1.059^4 = 1.26 > 1.25）。
 * 鳴らない段を作らないよう、ここで 3段に止める
 */
const MAX_STEPS = 3;

/**
 * 続きが切れるまでの時間（秒）。
 *
 * 魚の出る間隔（0.8〜2.0秒）＋ 出てくる 0.65秒 より少し長く取る。
 * 短いと、ふつうに遊んでいるだけで毎回切れて「上がらない」
 */
const CHAIN_SEC = 3.2;

export class HitChain {
  private steps = 0;
  private lastAt = -Infinity;

  /** 叩けた。**戻り値はその回の音の高さ**（1 が素のまま） */
  hit(now: number): number {
    if (now - this.lastAt > CHAIN_SEC) this.steps = 0;
    else this.steps = Math.min(MAX_STEPS, this.steps + 1);
    this.lastAt = now;
    return SEMITONE ** this.steps;
  }

  /** 外した。**元に戻すだけ**（元より低くはしない） */
  miss(): void {
    this.steps = 0;
    this.lastAt = -Infinity;
  }

  /** いま何段目か（開発と E2E 用） */
  describe(): { steps: number; pitch: number } {
    return { steps: this.steps, pitch: +(SEMITONE ** this.steps).toFixed(3) };
  }
}
