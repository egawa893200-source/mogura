/**
 * 動きを弱める指定（不変条件6）
 *
 * ==========================================================================
 * **`prefers-reduced-motion` は1箇所で読む。**
 *
 * `Ripple` が自前で `matchMedia` を呼んでいて、あとから足した効果
 * （しぶき・水たまりのゆれ）が**同じ指定を見ていなかった**。
 * 「ばあ！」で `AnimalConfig.style` を誰も読んでいなかったのと同じ形の抜けで、
 * **設定したのに半分しか効かない**という、いちばん気づきにくい壊れかたをする。
 *
 * **弱めるのは「動き」であって「反応」ではない。** 叩いたら必ず何かが返る
 * （不変条件1）のは変わらない —— 粒の数と揺れの角度を落とすだけ。
 *
 * **背景の動画は止めない。** 止めると「壊れた」に見えるうえ、
 * ゆっくり泳ぐ魚は不変条件6 が禁じている明滅でも急な揺れでもない。
 * ここで弱めるのは、こちらが作っている突発的な動きだけにしてある。
 * ==========================================================================
 */

/**
 * 「動きを減らして」と指定されているか。
 *
 * **DOM が無い環境（単体テスト）でも呼べる**こと。
 * 例外を投げてユーザーに見せない（§2）ので、読めなければ false
 */
export function prefersReducedMotion(): boolean {
  try {
    return globalThis.matchMedia?.('(prefers-reduced-motion: reduce)').matches ?? false;
  } catch {
    return false;
  }
}
